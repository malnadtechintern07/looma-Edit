  static List<AiPhotoPresetEntity> _cachedPresets = presets;

  static List<AiPhotoPresetEntity> get currentPresets => _cachedPresets;

  static Future<List<AiPhotoPresetEntity>> fetchServerPresets() async {
    try {
      final baseUrl = await ServerConfig.getBaseUrl();
      final uri = Uri.parse('$baseUrl/api/ai/presets?type=photo');
      final res = await ApiClient.get(uri);
      if (res.isOk && res.json is Map) {
        final json = res.json as Map<String, dynamic>;
        final listRaw = json['presets'] as List<dynamic>? ?? [];
        if (listRaw.isNotEmpty) {
          final fetched = listRaw.map((p) {
            var imgUrl = p['reference_image_url'] as String? ?? '';
            if (imgUrl.isNotEmpty) {
              if (imgUrl.startsWith('/')) {
                imgUrl = '$baseUrl$imgUrl';
              } else if (imgUrl.contains('localhost:5050') || imgUrl.contains('127.0.0.1:5050')) {
                imgUrl = imgUrl.replaceAll(RegExp(r'http://(localhost|127\.0\.0\.1):5050'), baseUrl);
              }
            }
            final tagsRaw = p['tags'] as String? ?? '';
            final tags = tagsRaw.split(',').map((s) => s.trim()).where((s) => s.isNotEmpty).toList();
            return AiPhotoPresetEntity(
              id: p['id']?.toString() ?? '',
              title: p['title'] as String? ?? 'AI Photo Preset',
              category: p['category'] as String? ?? 'Trending',
              prompt: p['prompt'] as String? ?? '',
              referenceImagePath: imgUrl.isNotEmpty ? imgUrl : 'assets/demo/ai_80s_synthwave.jpg',
              badgeText: '✨ ${(p['category'] as String? ?? 'AI').toUpperCase()}',
              styleKeywords: tags.isNotEmpty ? tags : ['AI', 'Masterpiece', '4K'],
              aspectRatio: '3:4',
              likesCount: 2400 + (p['display_order'] as int? ?? 0) * 120,
              negativePrompt: p['negative_prompt'] as String?,
              modelRecommendation: p['model_name'] as String?,
              lightingStyle: p['lighting'] as String?,
              cameraLens: p['camera_movement'] as String?,
            );
          }).toList();
          _cachedPresets = fetched;
          return fetched;
        }
      }
    } catch (_) {}
    return _cachedPresets;
  }

